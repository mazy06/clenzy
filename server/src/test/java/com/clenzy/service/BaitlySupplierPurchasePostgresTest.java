    @Test void concurrentBranchesCannotBothBeChosen() throws Exception {
        long id=create("RACE");
        try(var pool=Executors.newFixedThreadPool(2)) {
            var barrier=new CyclicBarrier(2);var internal=pool.submit(()->{barrier.await();try{invite(id);return true;}catch(IllegalArgumentException e){return false;}});
            var outside=pool.submit(()->{barrier.await();try{external(id);return true;}catch(IllegalArgumentException e){return false;}});
            assertThat(List.of(internal.get(15,TimeUnit.SECONDS),outside.get(15,TimeUnit.SECONDS))).containsExactlyInAnyOrder(true,false);
        }
    }
