    @Test void internalInvitationDoesNotGrantMembershipAndCreatesOneExactDebtOnlyAfterAcceptance() {
        long id=create("BILL-1");String token=invite(id);
        assertThatThrownBy(()->tx.execute(s->service.prepareExpense(id,"admin"))).hasMessageContaining("accepter");
        var claimed=tx.execute(s->service.claim(token,"supplier"));assertThat(claimed.get("amount")).isEqualTo(new BigDecimal("60.00"));
        long expense=tx.execute(s->service.prepareExpense(id,"admin"));long replay=tx.execute(s->service.prepareExpense(id,"admin"));assertThat(replay).isEqualTo(expense);
        verify(expenses,times(1)).saveAndFlush(argThat(e->e.getProvider().getId()==42 && e.getStatus()==ExpenseStatus.DRAFT && e.getAmountTtc().compareTo(new BigDecimal("60"))==0));
        assertThatThrownBy(()->external(id)).hasMessageContaining("compte Baitly");
        assertThatThrownBy(()->jdbc.getJdbcTemplate().update("UPDATE provider_expenses SET provider_id=1 WHERE id="+expense)).isInstanceOf(org.springframework.dao.DataIntegrityViolationException.class);
    }
