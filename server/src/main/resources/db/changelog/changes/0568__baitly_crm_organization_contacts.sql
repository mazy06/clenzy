-- Baitly CRM: retain historic records without manufacturing provenance or consent.
ALTER TABLE prospects ADD COLUMN contact_type varchar(40) NOT NULL DEFAULT 'PROVIDER',
    ADD COLUMN contact_nature varchar(40) NOT NULL DEFAULT 'UNKNOWN',
    ADD COLUMN source_type varchar(40) NOT NULL DEFAULT 'LEGACY',
    ADD COLUMN source_detail varchar(1000),
    ADD COLUMN source_url varchar(2000),
    ADD COLUMN source_recorded_at timestamptz,
    ADD COLUMN normalized_email varchar(255),
    ADD COLUMN normalized_phone varchar(40),
    ADD COLUMN archived boolean NOT NULL DEFAULT false,
    ADD COLUMN identity_version integer NOT NULL DEFAULT 0;
ALTER TABLE prospects DROP CONSTRAINT IF EXISTS prospects_category_check;
ALTER TABLE prospects ADD CONSTRAINT prospects_category_check CHECK
    (category IN ('CONCIERGERIES','MENAGE','ARTISANS','ENTRETIEN','BLANCHISSERIES','OWNERS','PROVIDERS'));
ALTER TABLE prospects ADD CONSTRAINT baitly_crm_type_check CHECK (contact_type IN ('OWNER','PROVIDER')),
    ADD CONSTRAINT baitly_crm_nature_check CHECK (contact_nature IN ('UNKNOWN','PRIVATE','PROFESSIONAL')),
    ADD CONSTRAINT baitly_crm_source_check CHECK (source_type IN ('LEGACY','MANUAL','CSV','REFERRAL','PARTNER','OPEN_DATA')),
    ADD CONSTRAINT baitly_crm_org_identity UNIQUE (organization_id,id);
UPDATE prospects SET normalized_email=nullif(lower(btrim(email)),''),
    normalized_phone=nullif(regexp_replace(regexp_replace(coalesce(phone,''),'[^0-9]','','g'),'^00',''),'');
-- Non-unique indexes intentionally preserve historic duplicates for review.
-- All CRM writes take the existing organization row lock before matching identities.
CREATE INDEX baitly_crm_email_idx ON prospects(organization_id,normalized_email);
CREATE INDEX baitly_crm_phone_idx ON prospects(organization_id,normalized_phone);
CREATE TABLE baitly_crm_contact_authorizations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id bigint NOT NULL,
    prospect_id bigint NOT NULL,
    channel varchar(255) NOT NULL CHECK (channel IN ('EMAIL','SMS','PHONE')),
    purpose varchar(255) NOT NULL CHECK (purpose IN ('MANAGEMENT','PROVIDER_RECRUITMENT')),
    basis varchar(255) NOT NULL CHECK (basis IN ('CONSENT','REQUESTED_CONTACT','B2B_LEGITIMATE_INTEREST')),
    decision varchar(255) NOT NULL CHECK (decision IN ('GRANTED','REVOKED')),
    evidence text NOT NULL CHECK (length(btrim(evidence))>0),
    destination_hash varchar(255) NOT NULL,
    identity_version integer NOT NULL,
    occurred_at timestamptz NOT NULL,
    recorded_at timestamptz NOT NULL,
    expires_at timestamptz,
    recorded_by varchar(255) NOT NULL,
    CONSTRAINT baitly_crm_authorization_contact FOREIGN KEY (organization_id,prospect_id)
        REFERENCES prospects(organization_id,id),
    CONSTRAINT baitly_crm_authorization_dates CHECK (occurred_at<=recorded_at AND (expires_at IS NULL OR expires_at>occurred_at))
);
CREATE INDEX baitly_crm_authorization_history ON baitly_crm_contact_authorizations(organization_id,prospect_id,id DESC);
CREATE INDEX baitly_crm_authorization_identity ON baitly_crm_contact_authorizations(organization_id,destination_hash);

