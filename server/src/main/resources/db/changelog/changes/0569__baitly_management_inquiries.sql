-- Matches Prospect/prospects, BaitlyPublicProfile/baitly_public_profiles and Organization/organizations.
ALTER TABLE prospects DROP CONSTRAINT baitly_crm_source_check;
ALTER TABLE prospects ADD CONSTRAINT baitly_crm_source_check CHECK
    (source_type IN ('LEGACY','MANUAL','CSV','REFERRAL','PARTNER','OPEN_DATA','PUBLIC_FORM'));
ALTER TABLE baitly_public_profiles ADD CONSTRAINT baitly_profile_org_identity UNIQUE (organization_id,id);
CREATE TABLE baitly_crm_management_inquiries (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id bigint NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
    prospect_id bigint NOT NULL,
    profile_id uuid,
    source_profile_id uuid NOT NULL,
    request_id uuid NOT NULL,
    purpose varchar(40) NOT NULL CHECK (purpose IN ('MANAGEMENT','ESTIMATE')),
    name varchar(255) NOT NULL,
    email varchar(255) NOT NULL,
    phone varchar(40),
    city varchar(150) NOT NULL,
    property_type varchar(40) NOT NULL CHECK (property_type IN ('APARTMENT','HOUSE','OTHER')),
    message text,
    reply_channel varchar(10) NOT NULL CHECK (reply_channel IN ('EMAIL','PHONE')),
    utm_source varchar(150), utm_medium varchar(150), utm_campaign varchar(150), referrer_host varchar(255),
    needs_review boolean NOT NULL DEFAULT false,
    notice_version varchar(40) NOT NULL,
    status varchar(40) NOT NULL DEFAULT 'NEW' CHECK (status IN ('NEW','IN_PROGRESS','CLOSED')),
    created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT baitly_inquiry_contact FOREIGN KEY (organization_id,prospect_id) REFERENCES prospects(organization_id,id),
    CONSTRAINT baitly_inquiry_profile FOREIGN KEY (organization_id,profile_id) REFERENCES baitly_public_profiles(organization_id,id) ON DELETE SET NULL (profile_id),
    CONSTRAINT baitly_inquiry_idempotence UNIQUE (organization_id,request_id),
    CONSTRAINT baitly_inquiry_reply CHECK (reply_channel<>'PHONE' OR nullif(btrim(phone),'') IS NOT NULL)
);
CREATE INDEX baitly_inquiry_inbox ON baitly_crm_management_inquiries(organization_id,id DESC);
CREATE INDEX baitly_inquiry_contact_history ON baitly_crm_management_inquiries(organization_id,prospect_id,id DESC);
