ALTER TABLE baitly_crm_contact_authorizations ADD CONSTRAINT baitly_crm_authorization_org_identity UNIQUE (organization_id,id);
CREATE TABLE baitly_crm_campaign_templates (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id bigint NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
    name varchar(150) NOT NULL, contact_type varchar(40) NOT NULL CHECK (contact_type IN ('OWNER','PROVIDER')),
    subject varchar(200) NOT NULL, body text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT baitly_campaign_template_org UNIQUE (organization_id,id)
);
CREATE TABLE baitly_crm_campaigns (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id bigint NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
    request_id uuid NOT NULL, template_id bigint NOT NULL, name varchar(150) NOT NULL,
    contact_type varchar(40) NOT NULL CHECK (contact_type IN ('OWNER','PROVIDER')),
    language varchar(2) NOT NULL CHECK (language IN ('fr','en','ar')),
    segment jsonb NOT NULL, subject varchar(200) NOT NULL, body text NOT NULL,
    organization_name varchar(200) NOT NULL,
    status varchar(40) NOT NULL DEFAULT 'READY' CHECK (status IN ('READY','ACTIVE','COMPLETED','CANCELLED')),
    created_by varchar(255) NOT NULL, created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT baitly_campaign_org UNIQUE (organization_id,id),
    CONSTRAINT baitly_campaign_request UNIQUE (organization_id,request_id),
    CONSTRAINT baitly_campaign_template FOREIGN KEY (organization_id,template_id) REFERENCES baitly_crm_campaign_templates(organization_id,id)
);
CREATE INDEX baitly_campaign_template_idx ON baitly_crm_campaigns(organization_id,template_id);
CREATE TABLE baitly_crm_campaign_recipients (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id bigint NOT NULL, campaign_id bigint NOT NULL, prospect_id bigint NOT NULL,
    email varchar(255) NOT NULL, destination_hash varchar(64) NOT NULL, identity_version integer NOT NULL,
    contact_name varchar(255) NOT NULL, subject varchar(255) NOT NULL, body text NOT NULL,
    authorization_id bigint,
    status varchar(40) NOT NULL DEFAULT 'QUEUED' CHECK (status IN ('QUEUED','SENDING','ACCEPTED','UNKNOWN','SKIPPED')),
    reason varchar(50), attempt_id uuid, attempted_at timestamptz, attempted_by varchar(255), accepted_at timestamptz, provider_message_id varchar(500),
    response_token_hash varchar(64) UNIQUE,
    CONSTRAINT baitly_recipient_org UNIQUE (organization_id,id),
    CONSTRAINT baitly_campaign_recipient_destination UNIQUE (organization_id,campaign_id,destination_hash),
    CONSTRAINT baitly_recipient_campaign FOREIGN KEY (organization_id,campaign_id) REFERENCES baitly_crm_campaigns(organization_id,id),
    CONSTRAINT baitly_recipient_contact FOREIGN KEY (organization_id,prospect_id) REFERENCES prospects(organization_id,id),
    CONSTRAINT baitly_recipient_authorization FOREIGN KEY (organization_id,authorization_id) REFERENCES baitly_crm_contact_authorizations(organization_id,id)
);
CREATE INDEX baitly_recipient_queue ON baitly_crm_campaign_recipients(organization_id,campaign_id,id);
CREATE INDEX baitly_recipient_contact_idx ON baitly_crm_campaign_recipients(organization_id,prospect_id,id DESC);
CREATE INDEX baitly_recipient_authorization_idx ON baitly_crm_campaign_recipients(organization_id,authorization_id) WHERE authorization_id IS NOT NULL;
CREATE TABLE baitly_crm_campaign_responses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id bigint NOT NULL, recipient_id bigint NOT NULL, request_id uuid NOT NULL,
    decision varchar(40) NOT NULL CHECK (decision IN ('INTERESTED','NOT_INTERESTED','QUESTION','UNSUBSCRIBE')),
    message text, source varchar(20) NOT NULL CHECK (source IN ('PUBLIC_LINK','MANUAL','ONE_CLICK')),
    recorded_by varchar(255) NOT NULL, created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT baitly_response_recipient FOREIGN KEY (organization_id,recipient_id) REFERENCES baitly_crm_campaign_recipients(organization_id,id),
    CONSTRAINT baitly_response_request UNIQUE (organization_id,recipient_id,request_id)
);
CREATE INDEX baitly_response_history ON baitly_crm_campaign_responses(organization_id,recipient_id,id DESC);
